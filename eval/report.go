// stageFloors are the refs decision.deny falls back to when the error carries
// no core.Denial. A block that lands on one is not misattributed — it is
// uncited, and the two are different findings about the decision trace, so the
// report keeps them apart.
var stageFloors = map[string]bool{
	"§7":                true,
	"ARCHITECTURE §3.1": true,
	"ARCHITECTURE §2.4": true,
}

// report writes the machine-readable artifacts and the summary table, and
// prints the summary to stdout. It reports; it does not pass or fail. A number
// that comes out badly is the measurement working.
func report(dir string, cases []Case, results []Result, samples []LatencySample, control string) error {
	if err := writeResultsCSV(filepath.Join(dir, "results.csv"), results); err != nil {
		return err
	}
	if err := writeLatencyCSV(filepath.Join(dir, "latency.csv"), samples); err != nil {
		return err
	}
	if err := writeJSON(filepath.Join(dir, "results.json"), map[string]any{
		"results": results, "latency": samples,
	}); err != nil {
		return err
	}
	s := summary(cases, results, samples, control)
	if err := os.WriteFile(filepath.Join(dir, "summary.md"), []byte(s), 0o644); err != nil {
		return err
	}
	fmt.Print(s)
	return nil
}

func writeResultsCSV(path string, results []Result) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	w := csv.NewWriter(f)
	if err := w.Write([]string{"name", "corpus", "class", "invariant", "profile", "depth", "tool",
		"expect", "decision", "ok", "want_ref", "ref", "stage", "detail", "wire_code",
		"latency_us", "overhead_us"}); err != nil {
		return err
	}
	for _, r := range results {
		if err := w.Write([]string{r.Name, r.Corpus, r.Class, r.Invariant, r.Profile,
			strconv.Itoa(r.Depth), r.Tool, r.Expect, r.Decision, strconv.FormatBool(r.OK),
			r.WantRef, r.Ref, r.Stage, oneLine(r.Detail), strconv.Itoa(r.WireCode),
			strconv.FormatInt(r.LatencyUS, 10), strconv.FormatInt(r.OverheadUS, 10)}); err != nil {
			return err
		}
	}
	w.Flush()
	return w.Error()
}

func writeLatencyCSV(path string, samples []LatencySample) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	w := csv.NewWriter(f)
	if err := w.Write([]string{"config", "depth", "n", "total_p50_us", "total_p99_us",
		"upstream_p50_us", "upstream_p99_us", "overhead_p50_us", "overhead_p99_us"}); err != nil {
		return err
	}
	for _, s := range samples {
		if err := w.Write([]string{s.Config, strconv.Itoa(s.Depth), strconv.Itoa(s.N),
			strconv.FormatInt(s.TotalP50, 10), strconv.FormatInt(s.TotalP99, 10),
			strconv.FormatInt(s.UpstreamP50, 10), strconv.FormatInt(s.UpstreamP99, 10),
			strconv.FormatInt(s.OverheadP50, 10), strconv.FormatInt(s.OverheadP99, 10)}); err != nil {
			return err
		}
	}
	w.Flush()
	return w.Error()
}

// rate is a counted proportion. Printing n/d beside the percentage is not
// decoration: "80%" over five cases and over five hundred are different claims.
type rate struct{ hit, n int }

func (r rate) String() string {
	if r.n == 0 {
		return "n/a (0 cases)"
	}
	return fmt.Sprintf("%5.1f%%  (%d/%d)", 100*float64(r.hit)/float64(r.n), r.hit, r.n)
}

func summary(cases []Case, results []Result, samples []LatencySample, control string) string {
	var b strings.Builder
	p := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }

	// Partition once. An adversarial case that expects a permit is a documented
	// non-block, and averaging it into the block rate would report a design
	// decision as a miss; it gets its own row instead.
	var advBlock, advNonBlock, benign []Result
	for _, r := range results {
		switch {
		case r.Corpus == "benign":
			benign = append(benign, r)
		case r.Expect == "permit":
			advNonBlock = append(advNonBlock, r)
		default:
			advBlock = append(advBlock, r)
		}
	}
	var buildErrs []Case
	for _, k := range cases {
		if k.BuildErr != "" {
			buildErrs = append(buildErrs, k)
		}
	}

	p("# M4 — adversarial evaluation")
	p("")
	p("Generated by `go run ./eval`. Method, corpus construction and limits: eval/METHOD.md.")
	p("")
	p("Cases: %d adversarial expecting a denial, %d adversarial expecting a permit",
		len(advBlock), len(advNonBlock))
	p("       (documented non-blocks), %d benign, %d never presented (build failed).",
		len(benign), len(buildErrs))
	p("")

	// --- block rate ---------------------------------------------------------
	p("## Block rate")
	p("")
	p("Adversarial cases warden is documented to deny. The decision is read from")
	p("the audit record, not the wire: a notification has no response.")
	p("")
	p("| corpus split | blocked |")
	p("|---|---|")
	p("| all | %s |", blockRate(advBlock, nil))
	p("| conformant draft-01 | %s |", blockRate(advBlock, isProfile("conformant")))
	p("| warden profile | %s |", blockRate(advBlock, isProfile("warden")))
	p("")
	p("This rate is a property of this corpus, not of warden. It says every attack")
	p("someone thought to write down was stopped; it cannot say anything about the")
	p("attacks nobody wrote. The corpus was written by the same author as the code,")
	p("which is the strongest reason to read it with suspicion, and the expected")
	p("non-blocks below are where the honest limits of the design are recorded.")
	p("")
	p("That is not a hypothetical caveat. The T1 framing cases were added after a")
	p("real client found the class they cover — a bypass that sat under a 100%%")
	p("block rate because no case in the corpus could express the message shape.")
	p("See eval/METHOD.md and docs/SHAKEDOWN.md.")
	p("")
	p("§3.1 control — a batch in `-passthrough-only`: %s.", control)
	p("Passthrough must relay what enforcing refuses, or the latency baseline is")
	p("measuring a second enforcing configuration.")
	p("")
	if miss := filter(advBlock, func(r Result) bool { return r.Decision != "deny" }); len(miss) > 0 {
		p("Not blocked, and not documented as a non-block — every one of these is a finding:")
		p("")
		for _, r := range miss {
			p("- **%s** (%s%s, %s): decided %q", r.Name, r.Class, invSuffix(r), r.Profile, r.Decision)
		}
		p("")
	}

	// --- attribution --------------------------------------------------------
	p("## Attribution of the blocks")
	p("")
	p("A block is not the whole result. SPEC contribution 3 is the decision trace,")
	p("so the case's `want_ref` is the finest clause true of that input and the run")
	p("reports whether the trace cited it. A block attributed to the wrong clause")
	p("still stops the call and still misleads the operator reading the log.")
	p("")
	blocked := filter(advBlock, func(r Result) bool { return r.Decision == "deny" && r.WantRef != "" })
	var exact, floor, wrong []Result
	for _, r := range blocked {
		switch {
		case r.Ref == r.WantRef:
			exact = append(exact, r)
		case stageFloors[r.Ref]:
			floor = append(floor, r)
		default:
			wrong = append(wrong, r)
		}
	}
	p("| outcome | share |")
	p("|---|---|")
	p("| blocked and correctly attributed | %s |", rate{len(exact), len(blocked)})
	p("| blocked, cited a different clause | %s |", rate{len(wrong), len(blocked)})
	p("| blocked, uncited (fell to the stage floor) | %s |", rate{len(floor), len(blocked)})
	p("")
	if len(wrong) > 0 {
		p("### Blocked but wrong clause")
		p("")
		p("Two different defects share this row, and the message column separates them:")
		p("a ref that is coarser than the wanted step but still contains it, and a ref")
		p("that names something not true of the input at all. Read the message beside")
		p("the ref before treating a row as either.")
		p("")
		p("| case | cited | true of this input | what the operator reads |")
		p("|---|---|---|---|")
		for _, r := range wrong {
			p("| %s | `%s` | `%s` | %s |", r.Name, r.Ref, r.WantRef, oneLine(r.Detail))
		}
		p("")
	}
	if len(floor) > 0 {
		p("### Blocked but uncited")
		p("")
		p("The trace fell to its stage floor: the refusal carries no `core.Denial`,")
		p("so the operator is told which stage refused and not which clause.")
		p("")
		p("| case | cited | true of this input | what the operator reads |")
		p("|---|---|---|---|")
		for _, r := range floor {
			p("| %s | `%s` | `%s` | %s |", r.Name, r.Ref, r.WantRef, oneLine(r.Detail))
		}
		p("")
	}

	// --- the documented non-blocks -----------------------------------------
	p("## Expected non-blocks")
	p("")
	p("Attacks in the corpus that warden permits, by a decision on record. They are")
	p("counted out of the block rate above and printed here, not in a footnote: a")
	p("block rate is only readable next to what was deliberately left unblocked.")
	p("")
	p("| case | class | decision | why |")
	p("|---|---|---|---|")
	for _, r := range advNonBlock {
		why := strings.TrimPrefix(r.Note, "KNOWN NON-BLOCK")
		why = strings.TrimLeft(why, " :")
		p("| %s | %s%s | %s | %s |", r.Name, r.Class, invSuffix(r), r.Decision, oneLine(why))
	}
	p("")
	if bad := filter(advNonBlock, func(r Result) bool { return r.Decision != "permit" }); len(bad) > 0 {
		p("Denied although documented as permitted — the documentation or the code is wrong:")
		p("")
		for _, r := range bad {
			p("- **%s**: %s at `%s`", r.Name, r.Decision, r.Ref)
		}
		p("")
	}

	// --- per class and per invariant ---------------------------------------
	p("## By threat class")
	p("")
	p("| class | blocked | non-blocks |")
	p("|---|---|---|")
	for _, c := range keysOf(advBlock, advNonBlock, func(r Result) string { return r.Class }) {
		p("| %s | %s | %d |", c,
			blockRate(advBlock, func(r Result) bool { return r.Class == c }),
			len(filter(advNonBlock, func(r Result) bool { return r.Class == c })))
	}
	p("")
	p("## By invariant")
	p("")
	p("Cases that attack a stated invariant. An adversarial case with no invariant")
	p("attacks the wire format or the transport binding rather than I1-I6.")
	p("")
	p("| invariant | blocked | non-blocks |")
	p("|---|---|---|")
	for _, i := range keysOf(advBlock, advNonBlock, func(r Result) string { return r.Invariant }) {
		if i == "" {
			continue
		}
		p("| %s | %s | %d |", i,
			blockRate(advBlock, func(r Result) bool { return r.Invariant == i }),
			len(filter(advNonBlock, func(r Result) bool { return r.Invariant == i })))
	}
	p("")

	// --- benign -------------------------------------------------------------
	fp := filter(benign, func(r Result) bool { return r.Decision != "permit" })
	p("## False positives")
	p("")
	p("Benign corpus: %d delegation scenarios warden SHOULD permit, built without", len(benign))
	p("reference to the adversarial corpus (eval/METHOD.md). Every denial here is a")
	p("finding to investigate, never a case to relabel.")
	p("")
	p("| | rate |")
	p("|---|---|")
	p("| denied | %s |", rate{len(fp), len(benign)})
	p("")
	for _, r := range fp {
		p("- **%s** (%s): denied at `%s`, stage %s", r.Name, r.Class, r.Ref, r.Stage)
	}
	if len(fp) > 0 {
		p("")
		p("Triage (M0b1's completeness probe): a denial whose cause is a missing witness")
		p("for a cross-type constraint pair is the 30.5%% default-deny population, not a bug;")
		p("anything else is.")
		p("")
	}

	// --- same-scope and build failures --------------------------------------
	if ss := sameScopeFindings(results); len(ss) > 0 {
		p("## same_scope mismatches")
		p("")
		p("§6 permits a derivation that attenuates nothing; ARCHITECTURE records it on")
		p("the permit instead. These cases expected a mark the record did not carry:")
		p("")
		for _, s := range ss {
			p("- %s", s)
		}
		p("")
	}
	if len(buildErrs) > 0 {
		p("## Never presented")
		p("")
		p("Construction failed, so warden never saw these. A benign case here is its own")
		p("finding: warden's §6 minting refused a delegation the corpus holds legitimate.")
		p("")
		for _, k := range buildErrs {
			p("- **%s** (%s): %s", k.Name, k.Corpus, oneLine(k.BuildErr))
		}
		p("")
	}

	// --- latency ------------------------------------------------------------
	p("## Latency")
	p("")
	p("M1's convention, unchanged so the three milestones compare: nearest-rank")
	p("percentiles, `overhead = total - upstream`, microseconds. `upstream` includes")
	p("pipe transit both ways, booked to the server's column by convention.")
	p("")
	p("| config | depth | n | total p50 | total p99 | upstream p50 | overhead p50 | overhead p99 |")
	p("|---|---|---|---|---|---|---|---|")
	for _, s := range samples {
		p("| %s | %d | %d | %s | %s | %s | %s | %s |", s.Config, s.Depth, s.N,
			us(s.TotalP50), us(s.TotalP99), us(s.UpstreamP50), us(s.OverheadP50), us(s.OverheadP99))
	}
	p("")
	p("The upstream is eval's own in-process test server answering in tens of")
	p("microseconds. Any percentage of total computed from these rows is a statement")
	p("about that peer, not about warden; the microseconds are the number that")
	p("transfers to a real server.")
	p("")
	return b.String()
}

func blockRate(rs []Result, keep func(Result) bool) rate {
	var r rate
	for _, x := range rs {
		if keep != nil && !keep(x) {
			continue
		}
		r.n++
		if x.Decision == "deny" {
			r.hit++
		}
	}
	return r
}

func isProfile(p string) func(Result) bool {
	return func(r Result) bool { return r.Profile == p }
}

func filter(rs []Result, keep func(Result) bool) []Result {
	var out []Result
	for _, r := range rs {
		if keep(r) {
			out = append(out, r)
		}
	}
	return out
}

// keysOf collects the distinct values of f across both slices, sorted, so the
// tables list what the corpus actually contains rather than a hardcoded T1..T6
// that would silently drop a class someone adds later.
func keysOf(a, bs []Result, f func(Result) string) []string {
	seen := map[string]bool{}
	for _, r := range append(append([]Result(nil), a...), bs...) {
		seen[f(r)] = true
	}
	out := make([]string, 0, len(seen))
	for k := range seen {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func sameScopeFindings(rs []Result) []string {
	var out []string
	for _, r := range rs {
		if r.WantSameScope == nil {
			continue
		}
		if fmt.Sprint(r.SameScope) != fmt.Sprint(r.WantSameScope) {
			out = append(out, fmt.Sprintf("**%s**: record carries %v, case expects %v",
				r.Name, r.SameScope, r.WantSameScope))
		}
	}
	return out
}

func invSuffix(r Result) string {
	if r.Invariant == "" {
		return ""
	}
	return "/" + r.Invariant
}

func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

func us(v int64) string {
	return fmt.Sprintf("%.3f ms", float64(v)/1000)
}
